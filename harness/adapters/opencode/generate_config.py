"""Generate the OpenCode-only role overlay used by the workshop launcher."""

from __future__ import annotations

import argparse
import json
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Literal, TypedDict, cast

import yaml

ADAPTER_DIRECTORY = Path(__file__).resolve().parent
REPOSITORY_DIRECTORY = ADAPTER_DIRECTORY.parents[2]
ROLE_DIRECTORY = REPOSITORY_DIRECTORY / "harness" / "roles"
PROFILE_PATH = ADAPTER_DIRECTORY / "profile.yaml"
DEFAULT_OUTPUT = ADAPTER_DIRECTORY / ".generated" / "opencode.jsonc"
SCHEMA_URL = "https://opencode.ai/config.json"
GENERATED_HEADER = "// Generated by generate_config.py. Do not edit.\n"

AgentMode = Literal["primary", "subagent"]
PermissionAction = Literal["allow", "ask", "deny"]


class ConfigurationError(ValueError):
    """Raised when a portable source cannot produce a valid OpenCode overlay."""


@dataclass(frozen=True)
class RolePrompt:
    role: str
    description: str
    prompt: str


@dataclass(frozen=True)
class PermissionSettings:
    edit: PermissionAction
    bash: PermissionAction
    task_roles: tuple[str, ...]


@dataclass(frozen=True)
class AgentSettings:
    role: str
    name: str
    model: str
    mode: AgentMode
    temperature: float
    variant: str
    permissions: PermissionSettings


class AgentPermission(TypedDict):
    edit: PermissionAction
    bash: PermissionAction
    task: PermissionAction | dict[str, PermissionAction]


class AgentDocument(TypedDict):
    description: str
    mode: AgentMode
    model: str
    temperature: float
    variant: str
    prompt: str
    permission: AgentPermission


OpenCodeDocument = TypedDict(
    "OpenCodeDocument",
    {"$schema": str, "agent": dict[str, AgentDocument]},
)


def mapping(value: object, location: str) -> Mapping[object, object]:
    if not isinstance(value, Mapping):
        raise ConfigurationError(f"{location} must be a mapping.")
    return value


def required_string(document: Mapping[object, object], key: str, location: str) -> str:
    value = document.get(key)
    if not isinstance(value, str) or not value.strip():
        raise ConfigurationError(f"{location}.{key} must be a non-empty string.")
    return value.strip()


def required_number(
    document: Mapping[object, object], key: str, location: str
) -> float:
    value = document.get(key)
    if isinstance(value, bool) or not isinstance(value, int | float):
        raise ConfigurationError(f"{location}.{key} must be a number.")
    return float(value)


def required_choice[T: str](
    document: Mapping[object, object],
    key: str,
    location: str,
    choices: tuple[T, ...],
) -> T:
    value = required_string(document, key, location)
    if value not in choices:
        allowed = ", ".join(choices)
        raise ConfigurationError(f"{location}.{key} must be one of: {allowed}.")
    return cast(T, value)


def required_strings(
    document: Mapping[object, object], key: str, location: str
) -> tuple[str, ...]:
    value = document.get(key)
    if not isinstance(value, list) or not all(
        isinstance(item, str) and item for item in value
    ):
        raise ConfigurationError(
            f"{location}.{key} must be a list of non-empty strings."
        )
    return tuple(value)


def read_yaml_mapping(path: Path) -> Mapping[object, object]:
    try:
        return mapping(yaml.safe_load(path.read_text(encoding="utf-8")), str(path))
    except yaml.YAMLError as error:
        raise ConfigurationError(f"{path} is not valid YAML: {error}") from error


def parse_role(path: Path) -> RolePrompt:
    content = path.read_text(encoding="utf-8")
    if not content.startswith("---\n"):
        raise ConfigurationError(f"{path} must begin with YAML front matter.")

    _, front_matter, prompt = content.split("---\n", maxsplit=2)
    metadata = mapping(yaml.safe_load(front_matter), f"{path} front matter")
    role = required_string(metadata, "role", f"{path} front matter")
    description = required_string(metadata, "description", f"{path} front matter")
    if not prompt.strip():
        raise ConfigurationError(
            f"{path} must include a prompt after its front matter."
        )
    return RolePrompt(role=role, description=description, prompt=prompt.strip())


def load_role_prompts() -> dict[str, RolePrompt]:
    role_paths = sorted(
        path for path in ROLE_DIRECTORY.glob("*.md") if path.name != "README.md"
    )
    if not role_paths:
        raise ConfigurationError(f"No role prompts found in {ROLE_DIRECTORY}.")

    prompts: dict[str, RolePrompt] = {}
    for path in role_paths:
        role_prompt = parse_role(path)
        if role_prompt.role in prompts:
            raise ConfigurationError(f"Duplicate role prompt: {role_prompt.role}.")
        prompts[role_prompt.role] = role_prompt
    return prompts


def parse_agent_settings(value: object, index: int) -> AgentSettings:
    location = f"{PROFILE_PATH}.agents[{index}]"
    document = mapping(value, location)
    permissions = mapping(document.get("permissions"), f"{location}.permissions")
    task_roles = required_strings(permissions, "task_roles", f"{location}.permissions")
    return AgentSettings(
        role=required_string(document, "role", location),
        name=required_string(document, "name", location),
        model=required_string(document, "model", location),
        mode=required_choice(document, "mode", location, ("primary", "subagent")),
        temperature=required_number(document, "temperature", location),
        variant=required_string(document, "variant", location),
        permissions=PermissionSettings(
            edit=required_choice(
                permissions, "edit", f"{location}.permissions", ("allow", "ask", "deny")
            ),
            bash=required_choice(
                permissions, "bash", f"{location}.permissions", ("allow", "ask", "deny")
            ),
            task_roles=task_roles,
        ),
    )


def load_agent_settings() -> tuple[AgentSettings, ...]:
    profile = read_yaml_mapping(PROFILE_PATH)
    raw_agents = profile.get("agents")
    if not isinstance(raw_agents, list) or not raw_agents:
        raise ConfigurationError(f"{PROFILE_PATH}.agents must be a non-empty list.")

    agents = tuple(
        parse_agent_settings(value, index) for index, value in enumerate(raw_agents)
    )
    roles = [agent.role for agent in agents]
    names = [agent.name for agent in agents]
    if len(roles) != len(set(roles)):
        raise ConfigurationError(f"{PROFILE_PATH} defines a role more than once.")
    if len(names) != len(set(names)):
        raise ConfigurationError(
            f"{PROFILE_PATH} defines an agent name more than once."
        )
    return agents


def agent_document(
    settings: AgentSettings,
    prompt: RolePrompt,
    agent_names_by_role: Mapping[str, str],
) -> AgentDocument:
    task_permissions: dict[str, PermissionAction] = {}
    for task_role in settings.permissions.task_roles:
        task_name = agent_names_by_role.get(task_role)
        if task_name is None:
            raise ConfigurationError(
                f"{PROFILE_PATH} assigns {settings.name} to an unknown task role: {task_role}."
            )
        task_permissions[task_name] = "allow"

    task: PermissionAction | dict[str, PermissionAction]
    if task_permissions:
        task = task_permissions
    else:
        task = "deny"

    return {
        "description": prompt.description,
        "mode": settings.mode,
        "model": settings.model,
        "temperature": settings.temperature,
        "variant": settings.variant,
        "prompt": prompt.prompt,
        "permission": {
            "edit": settings.permissions.edit,
            "bash": settings.permissions.bash,
            "task": task,
        },
    }


def config() -> OpenCodeDocument:
    prompts_by_role = load_role_prompts()
    settings = load_agent_settings()
    agent_names_by_role = {agent.role: agent.name for agent in settings}
    agents: dict[str, AgentDocument] = {}

    for agent_settings in settings:
        prompt = prompts_by_role.get(agent_settings.role)
        if prompt is None:
            raise ConfigurationError(
                f"{PROFILE_PATH} maps {agent_settings.name} to a missing role prompt: {agent_settings.role}."
            )
        agents[agent_settings.name] = agent_document(
            agent_settings, prompt, agent_names_by_role
        )

    return {"$schema": SCHEMA_URL, "agent": agents}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    args.output.parent.mkdir(parents=True, exist_ok=True)
    rendered = json.dumps(config(), indent=2)
    args.output.write_text(f"{GENERATED_HEADER}{rendered}\n", encoding="utf-8")


if __name__ == "__main__":
    main()
