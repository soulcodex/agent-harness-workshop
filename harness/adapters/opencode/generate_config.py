#!/usr/bin/env python3
"""Generate the OpenCode-only role overlay used by the workshop launcher."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


ADAPTER_DIRECTORY = Path(__file__).resolve().parent
DEFAULT_OUTPUT = ADAPTER_DIRECTORY / ".generated" / "opencode.jsonc"


def agent(
    *,
    description: str,
    mode: str,
    prompt: str,
    permission: dict[str, str | dict[str, str]],
) -> dict[str, object]:
    return {
        "description": description,
        "mode": mode,
        "prompt": prompt,
        "permission": permission,
    }


def config() -> dict[str, object]:
    return {
        "$schema": "https://opencode.ai/config.json",
        "agent": {
            "workshop-architect": agent(
                description="Scopes verified work and delegates bounded tasks.",
                mode="primary",
                prompt=(
                    "Act as the workshop architect. Follow the portable role contract routed by "
                    "the global AGENTS.md. Establish evidence, scope, acceptance criteria, and a "
                    "stop condition before delegating. Do not implement or approve a worker's change."
                ),
                permission={
                    "edit": "deny",
                    "bash": "ask",
                    "task": {
                        "workshop-researcher": "allow",
                        "workshop-worker": "allow",
                        "workshop-auditor": "allow",
                        "workshop-security-auditor": "allow",
                    },
                },
            ),
            "workshop-researcher": agent(
                description="Closes one evidence gap from a read-only context.",
                mode="subagent",
                prompt=(
                    "Act as the workshop researcher. Follow the portable role contract routed by "
                    "the global AGENTS.md. Resolve one evidence gap with local or authoritative "
                    "sources. Return sources, findings, and uncertainty. Do not edit or decide architecture."
                ),
                permission={"edit": "deny", "bash": "deny", "task": "deny"},
            ),
            "workshop-worker": agent(
                description="Implements one approved slice and returns deterministic evidence.",
                mode="subagent",
                prompt=(
                    "Act as the workshop worker. Follow the portable role contract routed by the "
                    "global AGENTS.md. Make only the approved change, run the narrowest relevant "
                    "deterministic checks, and return the diff, output, and warning disposition. Do not self-approve."
                ),
                permission={"edit": "allow", "bash": "allow", "task": "deny"},
            ),
            "workshop-auditor": agent(
                description="Independently reviews a supplied diff and its verification evidence.",
                mode="subagent",
                prompt=(
                    "Act as the workshop auditor. Follow the portable role contract routed by the "
                    "global AGENTS.md. Review only the supplied diff and verification evidence from "
                    "a fresh context. Return evidence-backed findings or approval. Do not edit."
                ),
                permission={"edit": "deny", "bash": "deny", "task": "deny"},
            ),
            "workshop-security-auditor": agent(
                description="Reviews reached trust boundaries and credible exploit paths.",
                mode="subagent",
                prompt=(
                    "Act as the workshop security auditor. Follow the portable role contract routed "
                    "by the global AGENTS.md. Review only reached trust boundaries and credible exploit "
                    "paths from a fresh context. Return evidence-backed findings or approval. Do not edit."
                ),
                permission={"edit": "deny", "bash": "deny", "task": "deny"},
            ),
        },
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    args.output.parent.mkdir(parents=True, exist_ok=True)
    rendered = json.dumps(config(), indent=2)
    args.output.write_text(f"// Generated by generate_config.py. Do not edit.\n{rendered}\n")


if __name__ == "__main__":
    main()
